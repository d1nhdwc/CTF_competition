#!/usr/bin/env python3
import itertools
import re
import sys
from pathlib import Path

ALLOWED_FLAG = set(b"abcdefghijklmnopqrstuvwxyz0123456789_{}")


def reverse_bits8(x: int) -> int:
    return int(f"{x:08b}"[::-1], 2)


def extension_high_nibble(key_byte: int) -> int:
    """
    Reproduce the deterministic upper nibble generated by block_encrypt().
    The lower nibble is random and therefore intentionally ignored.
    """
    out = 0
    for i in range(4):
        pair = (key_byte >> (2 * i)) & 0b11
        bit = (pair & 1) ^ (pair >> 1)
        out |= bit << (7 - i)
    return out & 0xF0


def is_lowercase_ascii(x: int) -> bool:
    return ord("a") <= x <= ord("z")


def parse_output(path: str) -> tuple[bytes, bytes]:
    text = Path(path).read_text()
    blobs = re.findall(r"(?m)^[0-9a-fA-F]+$", text)

    if len(blobs) < 2:
        raise ValueError("Could not find the two hexadecimal ciphertexts")

    garbage = bytes.fromhex(blobs[0])
    flag_ct = bytes.fromhex(blobs[1])

    if len(garbage) != 2 * len(flag_ct):
        raise ValueError("Expected garbage ciphertext to be twice the flag length")

    return garbage, flag_ct


def solve(path: str) -> None:
    garbage, flag_ct = parse_output(path)
    n = len(flag_ct)
    first, second = garbage[:n], garbage[n:]

    choices: list[list[int]] = []

    for i in range(n):
        possible_chars = set()

        for key_byte in range(256):
            # First garbage block: key_byte XOR lowercase plaintext.
            if not is_lowercase_ascii(first[i] ^ key_byte):
                continue

            # Second garbage block: deterministic high nibble plus an unknown
            # random low nibble, again XORed with lowercase plaintext.
            high = extension_high_nibble(key_byte)
            valid_second = any(
                is_lowercase_ascii(second[i] ^ (high | low))
                for low in range(16)
            )
            if not valid_second:
                continue

            flag_char = flag_ct[i] ^ reverse_bits8(key_byte)
            if flag_char in ALLOWED_FLAG:
                possible_chars.add(flag_char)

        if not possible_chars:
            raise RuntimeError(f"No candidate at position {i}")

        choices.append(sorted(possible_chars))

    candidates = [
        bytes(candidate).decode()
        for candidate in itertools.product(*choices)
    ]

    print("[+] Candidate flags:")
    for candidate in candidates:
        print("   ", candidate)

    # The leakage leaves only three o/_ ambiguities. The normal flag prefix
    # and the readable leetspeak sentence identify the intended candidate.
    intended = "bronco{n0t_r4nd0m_3nough}"
    if intended in candidates:
        print(f"\n[+] Flag: {intended}")
    else:
        print("\n[!] Intended candidate was not present; inspect the list above.")


if __name__ == "__main__":
    output_file = sys.argv[1] if len(sys.argv) > 1 else "output.txt"
    solve(output_file)